#!/usr/bin/env python3
"""Split the original dashboard fonts for on-demand web delivery.
Requires fonttools[woff]; original TTF files and their license stay unchanged.
"""
from pathlib import Path
from io import BytesIO
import hashlib, json
from fontTools import subset
from fontTools.ttLib import TTFont
ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / 'public/fonts'

def ranges(points):
    spans=[]
    for point in sorted(points):
        if spans and point == spans[-1][1] + 1: spans[-1][1] = point
        else: spans.append([point, point])
    return ','.join('U+%X'%a + ('-%X'%b if b != a else '') for a,b in spans)

def build():
    common=set(range(32,256)) | set(range(0x3000,0x3100)) | set(range(0xff00,0xfff0))
    for path in (ROOT/'public').rglob('*'):
        if path.suffix in {'.js','.html','.json'} and 'fonts' not in path.parts:
            common.update(map(ord,path.read_text()))
    destination=BASE/'web';destination.mkdir(exist_ok=True)
    faces=[];css=['/* Generated by packaging/build-web-fonts.py. Original Noto Sans JP, SIL OFL. */']
    for label,weight in [('Regular','100 500'),('Bold','600 900')]:
        raw=(BASE/f'NotoSansJP-{label}.ttf').read_bytes()
        source=TTFont(BytesIO(raw));supported=set(source.getBestCmap());source.close()
        frequent=sorted(supported & common);remaining=sorted(supported - common)
        groups=[frequent]+[remaining[i:i+1024] for i in range(0,len(remaining),1024)]
        files=[]
        for i,points in enumerate(groups):
            font=TTFont(BytesIO(raw));options=subset.Options();options.flavor='woff2'
            worker=subset.Subsetter(options=options);worker.populate(unicodes=points);worker.subset(font)
            font.flavor='woff2';out=BytesIO();font.save(out);font.close();data=out.getvalue()
            digest=hashlib.sha256(data).hexdigest();name=f'{label.lower()}-{i:02d}.{digest[:12]}.woff2'
            (destination/name).write_bytes(data)
            files.append({'file':name,'sha256':digest,'bytes':len(data),'codepoints':points})
            css.append('@font-face{font-family:"Bathjun Sans";font-style:normal;font-weight:%s;font-display:swap;src:url("./web/%s") format("woff2");unicode-range:%s}'%(weight,name,ranges(points)))
        faces.append({'weight':weight,'source':f'NotoSansJP-{label}.ttf','sourceSha256':hashlib.sha256(raw).hexdigest(),'files':files,'sourceGlyphCount':len(supported),'sourceCodepointsSha256':hashlib.sha256(','.join(map(str,sorted(supported))).encode()).hexdigest()})
        print(label, 'common:',len(frequent),'glyphs,',files[0]['bytes'],'bytes;',len(files),'files total')
    manifest={'family':'Bathjun Sans','faces':faces}
    (BASE/'web.json').write_text(json.dumps(manifest,separators=(',',':'))+'\n')
    (BASE/'web.css').write_text('\n'.join(css)+'\n')
    keep={f['file'] for face in faces for f in face['files']}
    for old in destination.glob('*.woff2'):
        if old.name not in keep:old.unlink()

if __name__ == '__main__': build()
